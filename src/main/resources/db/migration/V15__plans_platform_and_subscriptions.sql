-- 1. Global plans catalogue
CREATE TABLE plans (
    id                   bigint       GENERATED BY DEFAULT AS IDENTITY,
    code                 varchar(64)  NOT NULL,
    name                 varchar(255) NOT NULL,
    price                numeric(12, 2) NOT NULL,
    currency             varchar(8)   NOT NULL DEFAULT 'NGN',
    billing_period       varchar(32)  NOT NULL DEFAULT 'ANNUAL',
    per_user_price       numeric(12, 2),
    included_users       integer,
    ai_scanning_enabled  boolean      NOT NULL DEFAULT false,
    ecommerce_enabled    boolean      NOT NULL DEFAULT false,
    active               boolean      NOT NULL DEFAULT true,
    sort_order           integer      NOT NULL DEFAULT 0,
    created_at           timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_plans PRIMARY KEY (id),
    CONSTRAINT uk_plans_code UNIQUE (code)
);

