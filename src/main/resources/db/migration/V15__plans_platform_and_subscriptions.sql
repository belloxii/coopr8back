-- 2. Plan price audit log (append-only)
CREATE TABLE plan_price_audit (
    id                   bigint       GENERATED BY DEFAULT AS IDENTITY,
    plan_id              bigint       NOT NULL,
    old_price            numeric(12, 2) NOT NULL,
    new_price            numeric(12, 2) NOT NULL,
    old_per_user_price   numeric(12, 2),
    new_per_user_price   numeric(12, 2),
    changed_by           bigint       NOT NULL,
    changed_at           timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_plan_price_audit PRIMARY KEY (id),
    CONSTRAINT fk_plan_price_audit_plan FOREIGN KEY (plan_id) REFERENCES plans (id)
);

-- 3. Platform Super Admins (global)
CREATE TABLE platform_admins (
    id                   bigint       GENERATED BY DEFAULT AS IDENTITY,
    email                varchar(255) NOT NULL,
    password_hash        varchar(255) NOT NULL,
    status               varchar(32)  NOT NULL DEFAULT 'ACTIVE',
    created_at           timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at           timestamp(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_platform_admins PRIMARY KEY (id),
    CONSTRAINT uk_platform_admins_email UNIQUE (email)
);

